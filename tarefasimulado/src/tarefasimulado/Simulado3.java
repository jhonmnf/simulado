package tarefasimulado;

public class Simulado3 {
	public static void main(String[] args) {
		double numero1 = 20;
		double numero2 = 22;
		
		double somando = numero1 + numero2;
		double subtraindo = numero1 - numero2;
		double multiplicando = numero1 * numero2;
		double dividindo = numero1 / numero2;


		System.out.println("O valor da soma é: " + somando);
		System.out.println("O valor da subratraçao é: " + subtraindo);
		System.out.println("O valor da multiplicaçao é: " + multiplicando);
		System.out.println("O valor da divisao é: " + dividindo);
}
}